// DEV ONLY. Generates the plugin's data from the shared JSON (CLAUDE.md:
// data/ is plain JSON shared by both phases):
//   plugin/engine/generated/Schema.h   every parameter (schema order = engine order)
//   plugin/resources/presets.json      the bank and the Classic Basses, as engine values
//   npx tsx tools/gen-plugin-data.ts
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { params, patchToArray, validatePatch } from '../src/schema';
import { WOB_SHAPES, WOBBLE_BEATS } from '../src/engine/core/params';
import { WOB_TEMPLATES } from '../src/engine/core/wobshape';
import { categories } from '../src/quality/categories';
import { loadLibrary, ROOT } from './lib/data';

const q = (s: string) => JSON.stringify(s);
const lines = params.map((p) => {
  const type = { float: 'PType::Float', int: 'PType::Int', enum: 'PType::Enum', bool: 'PType::Bool' }[p.type];
  const def = p.type === 'enum' ? p.options!.indexOf(p.default as string) : p.type === 'bool' ? (p.default ? 1 : 0) : (p.default as number);
  const min = p.type === 'enum' ? 0 : p.type === 'bool' ? 0 : p.min!;
  const max = p.type === 'enum' ? p.options!.length - 1 : p.type === 'bool' ? 1 : p.max!;
  const curve = p.curve === 'log' ? 1 : p.curve === 'pow' ? 2 : 0;
  return `  { ${q(p.id)}, ${q(p.label)}, ${type}, ${min}, ${max}, ${def}, ${curve}, ${p.exponent ?? 3}, ${q(p.unit ?? '')}, ${q(p.group)}, ${q((p.options ?? []).join('|'))}, ${q(p.describes)} },`;
});
writeFileSync(join(ROOT, 'plugin/engine/generated/Schema.h'), `// GENERATED by tools/gen-plugin-data.ts from data/schema.json. Do not edit.
#pragma once
namespace lt {
enum class PType { Float, Int, Enum, Bool };
struct ParamSpec {
  const char* id; const char* label; PType type; double min, max, def; int curve; double exponent;
  const char* unit; const char* group; const char* options; const char* describes;
};
constexpr int PARAM_COUNT = ${params.length};
inline const ParamSpec PARAMS[PARAM_COUNT] = {
${lines.join('\n')}
};
} // namespace lt
`);

// The Wobbler: beats per cycle (by wobble.rate option) and its preset shapes' points (by wobble.shape option).
const num = (v: number) => (Number.isInteger(v) ? `${v}` : `${v}`);
const shapes = WOB_SHAPES.map((name) => WOB_TEMPLATES[name] ?? WOB_TEMPLATES.sine);
writeFileSync(join(ROOT, 'plugin/engine/generated/Wobble.h'), `// GENERATED by tools/gen-plugin-data.ts from data/schema.json and src/engine/core/wobshape.ts. Do not edit.
#pragma once
namespace lt {
constexpr int WOBBLE_RATE_COUNT = ${WOBBLE_BEATS.length};
constexpr double WOBBLE_BEATS[WOBBLE_RATE_COUNT] = {${WOBBLE_BEATS.map(num).join(', ')}};
constexpr int WOB_SHAPE_COUNT = ${shapes.length};
struct WobTemplate { int n; double xs[32]; double ys[32]; double ss[32]; };
inline const WobTemplate WOB_TEMPLATE_ARRAYS[WOB_SHAPE_COUNT] = {
${shapes.map((pts, i) => `  {${pts.length}, {${pts.map((q) => num(q.x)).join(', ')}}, {${pts.map((q) => num(q.y)).join(', ')}}, {${pts.map((q) => (q.s ? 1 : 0)).join(', ')}}}, // ${WOB_SHAPES[i]}`).join('\n')}
};
} // namespace lt
`);

// Presets: engine values in schema order, plus what the browser shows.
const TITLE: Record<string, string> = { bass: 'Dark Basses', lead: 'Leads', pad: 'Pads', pluck: 'Plucks', arp: 'Plucks', brass: 'Brass', choir: 'Choir', texture: 'Textures' };
const order = categories.map((c) => c.id);
const lib = loadLibrary().filter((e) => e.json.meta.collection === 'bank' || e.json.meta.collection === 'terror' || !e.json.meta.category);
const out = lib.map((e) => {
  const { patch } = validatePatch(e.json);
  const cat = e.json.meta.category as string | undefined;
  return {
    name: patch.meta.name,
    shelf: cat ? (TITLE[cat] ?? categories.find((c) => c.id === cat)!.name) : 'Classic Basses',
    rank: cat ? order.indexOf(cat === 'arp' ? 'pluck' : cat) : 999,
    description: patch.meta.description ?? '',
    values: Array.from(patchToArray(patch)),
  };
}).sort((a, b) => a.rank - b.rank || a.shelf.localeCompare(b.shelf));
writeFileSync(join(ROOT, 'plugin/resources/presets.json'), JSON.stringify(out.map(({ rank: _r, ...p }) => p)));
console.log(`${params.length} params, ${out.length} presets`);
