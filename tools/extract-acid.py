"""Dev only: the Acid wave's frames, taken straight from the owner's Serum Acid render (tools/waves/acid.wav).

The render is one note (f0 21.5409 Hz, one cycle = 2047.27 samples at 44.1 kHz, about one 2048 frame) swept through
the table: 40 cycles, the resonant peak going from harmonic 4 to 29. The whole file is resampled (FFT) so a cycle is
exactly 2048 samples, cut into its 40 cycles, each with its DC removed and peak-normalised, and written as int16 to
src/engine/core/acid-table.ts (base64) and plugin/engine/generated/AcidTable.h, the same numbers in both engines.

  python3 -I tools/extract-acid.py
"""
import base64, os, struct
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PERIOD = 44100 / 21.5409  # measured from the harmonic peaks
N = 2048


def read(path):
    b = open(path, 'rb').read()
    assert b[:4] == b'RIFF' and b[8:12] == b'WAVE'
    i, fmt, data = 12, None, None
    while i < len(b) - 8:
        cid, sz = b[i:i + 4], struct.unpack('<I', b[i + 4:i + 8])[0]
        body = b[i + 8:i + 8 + sz]
        if cid == b'fmt ': fmt = struct.unpack('<HHIIHH', body[:16])
        if cid == b'data': data = body
        i += 8 + sz + (sz & 1)
    ch, bits = fmt[1], fmt[5]
    return np.frombuffer(data, dtype='<f4' if bits == 32 else '<f8').reshape(-1, ch)[:, 0].astype(np.float64)


x = read(os.path.join(ROOT, 'tools/waves/acid.wav'))
m = int(round(len(x) * N / PERIOD))
X = np.fft.rfft(x)
Y = np.zeros(m // 2 + 1, dtype=complex)
k = min(len(X), len(Y))
Y[:k] = X[:k]
y = np.fft.irfft(Y, m) * m / len(x)
frames = []
for i in range(m // N):
    c = y[i * N:(i + 1) * N]
    c = c - c.mean()
    frames.append(c / np.abs(c).max())
q = np.round(np.array(frames) * 32767).astype('<i2')
print(len(frames), 'frames')

b64 = base64.b64encode(q.tobytes()).decode()
with open(os.path.join(ROOT, 'src/engine/core/acid-table.ts'), 'w') as f:
    f.write('// Generated by tools/extract-acid.py from the owner\'s Serum Acid render: do not edit.\n')
    f.write(f'export const ACID_FRAMES = {len(frames)};\n')
    f.write('/** The frames, 2048 int16 samples each, little-endian, base64. */\n')
    f.write(f"export const ACID_B64 =\n  '{b64}';\n")

with open(os.path.join(ROOT, 'plugin/engine/generated/AcidTable.h'), 'w') as f:
    f.write('// Generated by tools/extract-acid.py from the owner\'s Serum Acid render: do not edit.\n#pragma once\n#include <cstdint>\n\nnamespace lt {\n\n')
    f.write(f'constexpr int ACID_FRAMES = {len(frames)};\n')
    f.write(f'/** The frames, 2048 int16 samples each (as acid-table.ts). */\ninline constexpr int16_t ACID_TABLE[{len(frames)} * 2048] = {{\n')
    flat = q.reshape(-1)
    for i in range(0, len(flat), 32):
        f.write('  ' + ','.join(str(int(v)) for v in flat[i:i + 32]) + ',\n')
    f.write('};\n\n}  // namespace lt\n')
