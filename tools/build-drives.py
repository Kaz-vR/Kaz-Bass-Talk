"""Dev only: the drive models (owner's call, 27 Nov: the drives measured on the real units, not formulas).

Reads the models fitted by the reference harness (tools/ref-host + the identification in the scratch harness:
y = h(d) * post( f( g(d) * pre(x) ) ), f a table curve shared by every drive, g / h the reference's own drive gain
and output level at five drive settings, the measured tone as EQ bands before or after the curve) from
tools/drives/model_<type>.json, and writes them as data for both engines: src/engine/core/drive-models.ts and
plugin/engine/generated/DriveModels.h.

  python3 -I tools/build-drives.py
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# our drive types (grind<n>.drive_type order) and the unit each one is now measured from
TYPES = [('tape', 0, 'Soundtoys Decapitator, style A (Ampex 350)'), ('tube', 1, 'FabFilter Saturn 2, Warm Tube'),
         ('amp', 2, 'FabFilter Saturn 2, British Rock Amp'), ('soft', 3, 'FabFilter Saturn 2, Gentle Saturation'),
         ('fold', 5, 'FabFilter Saturn 2, Foldback'), ('rect', 6, 'FabFilter Saturn 2, Rectify'),
         ('starved', 9, 'FabFilter Saturn 2, Broken Tube')]
KIND = {'hp2': 0, 'lp2': 1, 'peak': 2}
models = []
for name, idx, src in TYPES:
    m = json.load(open(os.path.join(ROOT, 'tools/drives', f'model_{name}.json')))
    k = m['knots']
    pre = m.get('eq_pre', m['eq'] if m['where'] == 'pre' else [])
    post = m.get('eq_post', m['eq'] if m['where'] != 'pre' else [])
    pad = lambda bands: ([[KIND[e[0]], float(e[1]), float(e[2]), float(e[3])] for e in bands] + [[2, 1000.0, 0.0, 1.0]] * 5)[:5]
    models.append(dict(name=name, type=idx, source=src, drives=m['drives'], gains=m['gains'], outs=m['outs'], k0=k[0], dk=k[1] - k[0],
                       curve=m['curve'], eqpre=pad(pre), eqpost=pad(post), error=m['error']))
    print(f"{name:8s} from {src}: model error {m['error']:.3f}, filters {m['where']}")
fmt = lambda v: repr(round(float(v), 7))
with open(os.path.join(ROOT, 'src/engine/core/drive-models.ts'), 'w') as o:
    o.write("// Generated by tools/build-drives.py from the drive models measured on the real units: do not edit.\n")
    o.write("/** One drive type: EQ bands [kind (0 hp2, 1 lp2, 2 peak), Hz, dB, Q] before (eqPre) and after (eqPost) the curve; the\n * curve's values on knots k0 + i dk; the unit's drive gain and output level at its drive settings. */\n")
    o.write("export interface DriveModel { type: number; drives: number[]; gains: number[]; outs: number[]; k0: number; dk: number; curve: number[]; eqPre: number[][]; eqPost: number[][] }\n")
    o.write("export const DRIVE_MODELS: DriveModel[] = [\n")
    for m in models:
        o.write(f"  // {m['name']}: {m['source']} (model error {m['error']:.3f})\n")
        o.write(f"  {{ type: {m['type']}, drives: [{', '.join(fmt(v) for v in m['drives'])}], gains: [{', '.join(fmt(v) for v in m['gains'])}],\n")
        o.write(f"    outs: [{', '.join(fmt(v) for v in m['outs'])}], k0: {fmt(m['k0'])}, dk: {fmt(m['dk'])},\n")
        o.write(f"    curve: [{', '.join(fmt(v) for v in m['curve'])}],\n")
        o.write(f"    eqPre: [{', '.join('[' + ', '.join(fmt(v) for v in e) + ']' for e in m['eqpre'])}],\n")
        o.write(f"    eqPost: [{', '.join('[' + ', '.join(fmt(v) for v in e) + ']' for e in m['eqpost'])}] }},\n")
    o.write("];\n")
with open(os.path.join(ROOT, 'plugin/engine/generated/DriveModels.h'), 'w') as o:
    o.write("// Generated by tools/build-drives.py from the drive models measured on the real units: do not edit.\n#pragma once\n\nnamespace lt {\n\n")
    n = len(models); nd = len(models[0]['drives']); nk = len(models[0]['curve']); ne = 5
    o.write(f"constexpr int DRIVE_MODEL_COUNT = {n}, DRIVE_MODEL_DRIVES = {nd}, DRIVE_MODEL_KNOTS = {nk}, DRIVE_MODEL_EQ = {ne};\n")
    o.write("struct DriveModel { int type; double drives[DRIVE_MODEL_DRIVES], gains[DRIVE_MODEL_DRIVES], outs[DRIVE_MODEL_DRIVES], k0, dk, curve[DRIVE_MODEL_KNOTS], eqPre[DRIVE_MODEL_EQ][4], eqPost[DRIVE_MODEL_EQ][4]; };\n")
    o.write("inline const DriveModel DRIVE_MODELS[DRIVE_MODEL_COUNT] = {\n")
    for m in models:
        o.write(f"  // {m['name']}: {m['source']}\n")
        o.write(f"  {{{m['type']}, {{{', '.join(fmt(v) for v in m['drives'])}}}, {{{', '.join(fmt(v) for v in m['gains'])}}}, {{{', '.join(fmt(v) for v in m['outs'])}}}, {fmt(m['k0'])}, {fmt(m['dk'])},\n")
        o.write(f"   {{{', '.join(fmt(v) for v in m['curve'])}}},\n")
        o.write(f"   {{{', '.join('{' + ', '.join(fmt(v) for v in e) + '}' for e in m['eqpre'])}}},\n")
        o.write(f"   {{{', '.join('{' + ', '.join(fmt(v) for v in e) + '}' for e in m['eqpost'])}}}}},\n")
    o.write("};\n\n}  // namespace lt\n")
